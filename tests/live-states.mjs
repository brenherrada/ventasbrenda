import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const pw = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.QA_URL || 'https://localhost:8768';
const out = 'output/qa/release-2026-10-08';
const browser = await pw.chromium.launch();
const observations = [];
for (const width of [390, 1440]) {
  const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width, height: width === 390 ? 844 : 1000 } });
  const page = await context.newPage();
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('#products').getAttribute('aria-busy') === 'false' && document.querySelector('.card[data-id]'));
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => document.querySelector('.hero-visual img').complete);
  await page.screenshot({ path: `${out}/review-${width}-hero.png` });
  observations.push(await page.locator('.hero-visual img').evaluate(e => ({ width: innerWidth, source: e.currentSrc, natural: [e.naturalWidth, e.naturalHeight], rendered: [e.clientWidth, e.clientHeight], heroHeight: document.querySelector('.hero-wrap').clientHeight })));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('#catalogo').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => [...document.querySelectorAll('.media-button > img')].filter(e => e.getBoundingClientRect().top < innerHeight).every(e => e.complete && e.naturalWidth));
  await page.screenshot({ path: `${out}/review-${width}-catalog.png` });
  await page.locator(width === 390 ? '.mobile-nav .catalog-trigger' : '.header-links .catalog-trigger').click();
  await page.screenshot({ path: `${out}/review-${width}-menu.png` });
  await page.keyboard.press('Escape');
  await page.locator('.media-button').first().click();
  await page.waitForFunction(() => document.querySelector('#lightboxImage').complete && document.querySelector('#lightboxImage').naturalWidth > 0);
  await page.screenshot({ path: `${out}/review-${width}-gallery.png` });
  await page.keyboard.press('Escape');
  for (const i of [0, 1, 2, 3]) await page.locator('.select-btn').nth(i).click();
  await page.locator(width === 390 ? '#openBagMobile' : '#openBag').click();
  await page.screenshot({ path: `${out}/review-${width}-cart.png` });
  await page.locator('.drawer-body').evaluate(e => e.scrollTop = e.scrollHeight);
  await page.screenshot({ path: `${out}/review-${width}-cart-form.png` });
  await page.keyboard.press('Escape');
  await page.locator('#webPromoTrigger').click();
  await page.waitForFunction(() => document.querySelector('.web-promo-art').complete && document.querySelector('.web-promo-art').naturalWidth > 0);
  await page.screenshot({ path: `${out}/review-${width}-promo.png` });
  await context.close();
}
await writeFile(`${out}/hero-sources.json`, JSON.stringify(observations, null, 2));
console.log(observations);
await browser.close();
